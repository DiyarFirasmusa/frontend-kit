import {
  DENSITY,
  FONT_SIZES,
  FONTS,
  MOTION,
  RADII,
  SHADOWS,
  SPACING,
  TYPE_RAMP,
} from './foundation.ts';
import { DEFAULT_PRESET_ID, PRESETS } from './presets/index.ts';
import { statusTokens } from './status.ts';
import {
  ALIAS_TOKENS,
  PRESET_TOKEN_NAMES,
  type Mode,
  type Preset,
} from './types.ts';

const HEADER = `/* GENERATED by \`npm run tokens\` from src/style/tokens. Do not edit by hand. */`;

/** Every colour token name a component can use, preset-independent. */
export function allColourTokenNames(): string[] {
  const probe = PRESETS[0];
  if (!probe) {
    throw new Error('no presets defined');
  }
  const status = Object.keys(statusTokens('light', probe.light));
  return [...PRESET_TOKEN_NAMES, ...status, ...Object.keys(ALIAS_TOKENS)];
}

/** `text-b2` -> `font-b2`: the CSS variable behind a type-ramp utility. */
export function rampVar(utility: string): string {
  return `font-${utility.replace(/^text-/u, '')}`;
}

function declarations(values: Readonly<Record<string, string>>): string {
  return Object.entries(values)
    .map(([name, value]) => `  --${name}: ${value};`)
    .join('\n');
}

/** The literal colour values of one preset in one mode (presets + status + tags). */
export function modeValues(
  preset: Preset,
  mode: Mode,
): Readonly<Record<string, string>> {
  const tokens = preset[mode];
  return { ...tokens, ...statusTokens(mode, tokens) };
}

/** `theme.css`: non-colour tokens, the Tailwind theme map and the type ramp. */
export function generateTheme(): string {
  const colourMap = allColourTokenNames()
    .map((name) => `  --color-${name}: var(--${name});`)
    .join('\n');
  const spacing = Object.entries(SPACING)
    .map(([role, value]) => `  --spacing-${role}: ${value};`)
    .join('\n');
  const sizes = FONT_SIZES.map(
    ([key, size, line]) =>
      `  --text-${key}: ${size};\n  --text-${key}--line-height: ${line};`,
  ).join('\n');
  const radii = Object.entries(RADII)
    .map(([key, value]) => `  --radius-${key}: ${value};`)
    .join('\n');
  const shadows = Object.entries(SHADOWS)
    .map(([key, value]) => `  --shadow-${key}: ${value};`)
    .join('\n');

  const rampVars = Object.entries(TYPE_RAMP)
    .map(
      ([name, s]) =>
        `  --${rampVar(name)}: ${s.weight} ${s.size}px / ${s.line}px var(--font-${s.family});`,
    )
    .join('\n');
  const ramp = Object.keys(TYPE_RAMP)
    .map((name) => `@utility ${name} {\n  font: var(--${rampVar(name)});\n}`)
    .join('\n');

  return `${HEADER}

@theme inline {
  /* Typefaces */
  --font-sans: ${FONTS.sans};
  --font-heading: ${FONTS.heading};
  --font-mono: ${FONTS.mono};

  /* Colours: every token is a var() so presets and dark mode switch at runtime */
${colourMap}

  /* Spacing by role (gap-field, p-card, space-y-card ...) */
${spacing}

  /* Font-size scale */
${sizes}

  /* Radii */
${radii}

  /* Elevation */
${shadows}

  /* Motion: ease-standard is also a utility */
  --ease-standard: ${MOTION['ease-standard']};
}

:root {
  --radius: 0.75rem;
  color-scheme: light;

  /* Motion */
  --ease-standard: ${MOTION['ease-standard']};
  --duration-fast: ${MOTION['duration-fast']};
  --duration-base: ${MOTION['duration-base']};
  --duration-slow: ${MOTION['duration-slow']};

  /* Type ramp as font shorthands: component CSS writes font: var(--font-b2)
     and follows TYPE_RAMP like the text-b2 utility does. */
${rampVars}

  /* Density (comfortable is the default) */
${declarations(DENSITY.comfortable)}

  /* Theme-ripple defaults; the theme provider sets x/y/r per switch */
  --vt-x: 50%;
  --vt-y: 50%;
  --vt-r: 150vmax;
  --vt-duration: 420ms;
  --vt-easing: cubic-bezier(0.4, 0, 0.9, 1);
}

:root.dark {
  color-scheme: dark;
}

:root[data-density='compact'] {
${declarations(DENSITY.compact)}
}

${ramp}
`;
}

function presetSelectors(preset: Preset, mode: Mode): string {
  const isDefault = preset.id === DEFAULT_PRESET_ID;
  const base = `:root[data-preset='${preset.id}']`;
  const dark = mode === 'dark' ? '.dark' : '';
  if (isDefault) {
    // The default preset also answers when <html> has no data-preset at all.
    return `:root${dark},\n${base}${dark}`;
  }
  return `${base}${dark}`;
}

/** `preset.css`: aliases once, then light and dark colours for every preset. */
export function generatePreset(): string {
  const aliases = Object.entries(ALIAS_TOKENS)
    .map(([name, target]) => `  --${name}: var(--${target});`)
    .join('\n');
  const blocks = PRESETS.flatMap((preset) =>
    (['light', 'dark'] as const).map(
      (mode) =>
        `/* ${preset.label} (${mode}) */\n${presetSelectors(preset, mode)} {\n${declarations(modeValues(preset, mode))}\n}`,
    ),
  ).join('\n\n');
  return `${HEADER}

/* Aliases: one var() each, resolved against whichever preset and mode is active. */
:root {
${aliases}
}

${blocks}
`;
}
