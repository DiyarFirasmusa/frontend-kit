import {
  CONTAINERS,
  DENSITY,
  FONT_SIZES,
  FONT_STACKS,
  FONTS,
  MOTION,
  RADII,
  SHADOWS,
  SPACING,
  TYPE_RAMP,
} from './foundation.ts';
import { DEFAULT_PRESET_ID, PRESETS } from './presets/index.ts';
import { statusTokens } from './status.ts';
import { ALIAS_TOKENS, PRESET_TOKEN_NAMES, type Mode, type Preset } from './types.ts';

const HEADER = `/* GENERATED by \`npm run tokens\` from src/style/tokens. Do not edit by hand. */`;

/** Every colour token name a component can use, preset-independent. */
export function allColourTokenNames(): string[] {
  const probe = PRESETS[0];
  if (!probe) {
    throw new Error('no presets defined');
  }
  const status = Object.keys(statusTokens('light', probe.light));
  return [...PRESET_TOKEN_NAMES, ...status, ...Object.keys(ALIAS_TOKENS)];
}

function declarations(values: Readonly<Record<string, string>>, indent = '  '): string {
  return Object.entries(values)
    .map(([name, value]) => `${indent}--${name}: ${value};`)
    .join('\n');
}

/** The literal colour values of one preset in one mode (presets + status + tags). */
export function modeValues(preset: Preset, mode: Mode): Readonly<Record<string, string>> {
  const tokens = preset[mode];
  return { ...tokens, ...statusTokens(mode, tokens) };
}

/** `theme.css`: non-colour tokens, the Tailwind theme map and the type ramp. */
export function generateTheme(): string {
  const colourMap = allColourTokenNames()
    .map((name) => `  --color-${name}: var(--${name});`)
    .join('\n');
  const spacing = Object.entries(SPACING)
    .map(([role, value]) => `  --spacing-${role}: ${value};`)
    .join('\n');
  const containers = Object.entries(CONTAINERS)
    .map(([name, value]) => `  --container-${name}: ${value};`)
    .join('\n');
  const sizes = FONT_SIZES.map(
    ([key, size, line]) => `  --text-${key}: ${size};\n  --text-${key}--line-height: ${line};`,
  ).join('\n');
  const radii = Object.entries(RADII)
    .map(([key, value]) => `  --radius-${key}: ${value};`)
    .join('\n');
  const shadows = Object.entries(SHADOWS)
    .map(([key, value]) => `  --shadow-${key}: ${value};`)
    .join('\n');

  const ramp = Object.entries(TYPE_RAMP)
    .map(
      ([name, s]) =>
        `@utility ${name} {\n  font: ${s.weight} ${s.size}px / ${s.line}px var(--font-${s.family});\n}`,
    )
    .join('\n');

  return `${HEADER}

@theme inline {
  /* Typefaces: --font-body follows <html lang> (below) */
  --font-sans: ${FONTS.sans};
  --font-heading: ${FONTS.heading};
  --font-mono: ${FONTS.mono};

  /* Colours: every token is a var() so presets and dark mode switch at runtime */
${colourMap}

  /* Spacing by role (gap-field, p-card, px-gutter, py-section ...) */
${spacing}

  /* Content widths (max-w-page, max-w-prose) */
${containers}

  /* Font-size scale */
${sizes}

  /* Radii */
${radii}

  /* Elevation */
${shadows}

  /* Motion: ease-standard is also a utility */
  --ease-standard: ${MOTION['ease-standard']};
}

:root {
  --radius: 0.75rem;
  color-scheme: light;

  /* Fonts */
  --font-stack-arabic: ${FONT_STACKS.arabic};
  --font-stack-latin: ${FONT_STACKS.latin};
  --font-body: var(--font-stack-latin);

  /* Motion */
  --ease-standard: ${MOTION['ease-standard']};
  --duration-fast: ${MOTION['duration-fast']};
  --duration-base: ${MOTION['duration-base']};
  --duration-slow: ${MOTION['duration-slow']};

  /* Density (comfortable is the default) */
${declarations(DENSITY.comfortable)}
}

:root:lang(ar) {
  --font-body: var(--font-stack-arabic);
}

:root[data-theme='dark'] {
  color-scheme: dark;
}

@media (prefers-color-scheme: dark) {
  :root:not([data-theme='light']) {
    color-scheme: dark;
  }
}

:root[data-density='compact'] {
${declarations(DENSITY.compact)}
}

${ramp}
`;
}

/**
 * Selectors for one preset in one mode. Dark mode has two triggers: the visitor's saved choice
 * (data-theme="dark", set before first paint) and, with no saved choice, the system setting.
 * So a page is right even before any JavaScript runs.
 */
function presetSelectors(preset: Preset, mode: Mode): { plain: string; media?: string } {
  const bases =
    preset.id === DEFAULT_PRESET_ID
      ? // The default preset also answers when <html> has no data-preset at all.
        [':root', `:root[data-preset='${preset.id}']`]
      : [`:root[data-preset='${preset.id}']`];
  if (mode === 'light') {
    return { plain: bases.join(',\n') };
  }
  return {
    plain: bases.map((base) => `${base}[data-theme='dark']`).join(',\n'),
    media: bases.map((base) => `${base}:not([data-theme='light'])`).join(',\n'),
  };
}

function presetBlock(preset: Preset, mode: Mode): string {
  const values = modeValues(preset, mode);
  const { plain, media } = presetSelectors(preset, mode);
  const comment = `/* ${preset.label} (${mode}) */`;
  const block = `${plain} {\n${declarations(values)}\n}`;
  if (media === undefined) {
    return `${comment}\n${block}`;
  }
  const mediaBlock = `@media (prefers-color-scheme: dark) {\n  ${media.replaceAll('\n', '\n  ')} {\n${declarations(values, '    ')}\n  }\n}`;
  return `${comment}\n${block}\n\n${mediaBlock}`;
}

/** `preset.css`: aliases once, then light and dark colours for every preset. */
export function generatePreset(): string {
  const aliases = Object.entries(ALIAS_TOKENS)
    .map(([name, target]) => `  --${name}: var(--${target});`)
    .join('\n');
  const blocks = PRESETS.flatMap((preset) =>
    (['light', 'dark'] as const).map((mode) => presetBlock(preset, mode)),
  ).join('\n\n');
  return `${HEADER}

/* Aliases: one var() each, resolved against whichever preset and mode is active. */
:root {
${aliases}
}

${blocks}
`;
}
